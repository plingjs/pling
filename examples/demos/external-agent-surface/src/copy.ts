export function copyFor(locale: DemoLocale) {
  return COPY[locale];
}

export function priorityLabel(locale: DemoLocale, priority: Priority): string {
  const copy = copyFor(locale);
  return priority === "today" ? copy.today : priority === "soon" ? copy.soon : copy.later;
}
